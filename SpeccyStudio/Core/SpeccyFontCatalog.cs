    public static IEnumerable<SpriteBankItem> GetFontItems(string game)
    {
        bool isRex = game.Contains("Rex", StringComparison.OrdinalIgnoreCase);
        var font = isRex ? RexFont : MythFont;
        string gameTitle = isRex ? "Rex (1988) [128K]" : "Myth (1989) [128K]";
        byte attr = isRex ? (byte)0x45 : (byte)0x46; // Bright Cyan for Rex Sci-Fi, Bright Yellow for Myth Rune

        foreach (var (ch, glyph) in font)
        {
            string id = $"FONT_{(isRex ? "REX" : "MYTH")}_{(int)ch:X2}";
            string name = $"Font '{(ch == ' ' ? "Space" : ch.ToString())}'";
            yield return new SpriteBankItem(
                Id: id,
                Name: name,
                SourceGame: gameTitle,
                Category: "Fonts & Typography",
                WidthCells: 1,
                HeightCells: 1,
                Bitmap: (byte[])glyph.Clone(),
                Attributes: [attr],
                Description: $"Authentic 8×8 {(isRex ? "Sci-Fi HUD font" : "Stone-Tablet Rune font")} character '{ch}'.",
                Tags: $"font,typography,8x8,{(isRex ? "rex,scifi" : "myth,rune")}");
        }
    }
